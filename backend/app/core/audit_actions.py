from enum import StrEnum


class AuditAction(StrEnum):
    """Controlled vocabulary for system audit actions."""

    # Authentication & User Actions
    AUTH_LOGIN = "AUTH_LOGIN"
    AUTH_LOGIN_FAILED = "AUTH_LOGIN_FAILED"
    AUTH_LOGOUT = "AUTH_LOGOUT"

    # Tender Management
    TENDER_CREATED = "TENDER_CREATED"
    TENDER_UPDATED = "TENDER_UPDATED"
    REQUIREMENT_CREATED = "REQUIREMENT_CREATED"
    REQUIREMENT_UPDATED = "REQUIREMENT_UPDATED"

    # Bid Submission Management
    BID_SUBMISSION_CREATED = "BID_SUBMISSION_CREATED"
    BID_SUBMISSION_UPDATED = "BID_SUBMISSION_UPDATED"

    # Document & OCR Lifecycle
    DOCUMENT_UPLOADED = "DOCUMENT_UPLOADED"
    DOCUMENT_PROCESSING_STARTED = "DOCUMENT_PROCESSING_STARTED"
    DOCUMENT_PROCESSING_COMPLETED = "DOCUMENT_PROCESSING_COMPLETED"
    DOCUMENT_PROCESSING_FAILED = "DOCUMENT_PROCESSING_FAILED"
    DOCUMENT_EXTRACTION_CREATED = "DOCUMENT_EXTRACTION_CREATED"

    # Portal Verification
    VERIFICATION_STARTED = "VERIFICATION_STARTED"
    VERIFICATION_COMPLETED = "VERIFICATION_COMPLETED"
    VERIFICATION_FAILED = "VERIFICATION_FAILED"
    CROSS_VERIFICATION_COMPLETED = "CROSS_VERIFICATION_COMPLETED"

    # Discrepancy Lifecycle
    DISCREPANCY_CREATED = "DISCREPANCY_CREATED"
    DISCREPANCY_RESOLVED = "DISCREPANCY_RESOLVED"
    DISCREPANCY_WAIVED = "DISCREPANCY_WAIVED"

    # Compliance & Risk Assessment
    COMPLIANCE_EVALUATED = "COMPLIANCE_EVALUATED"
    ASSESSMENT_CREATED = "ASSESSMENT_CREATED"
    ASSESSMENT_UPDATED = "ASSESSMENT_UPDATED"
    RECOMMENDATION_GENERATED = "RECOMMENDATION_GENERATED"
    PROCUREMENT_DECISION_CREATED = "PROCUREMENT_DECISION_CREATED"


